import collectionsJson from "@/generated/collections.json";
import elementsJson from "@/generated/elements.json";

import type { RegistryFile } from "@/lib/registry-files";

/** An observed attribute of a custom element and its React prop. */
export type AttributeMeta = { name: string; prop: string; type: "string" | "number" | "boolean" | "json" };
/** An event and its React handler prop. */
export type EventMeta = { name: string; prop: string; detail: string[] };
/** A prop of a native React component. */
export type PropMeta = { name: string; type: string; default: string };
/** A playground control. */
export type ControlMeta = { name: string; kind: "enum" | "boolean" | "number" | "string"; options: string[] | null; default: string | null };

/** One component, as scripts/catalog.mjs writes it to src/generated/elements.json. */
export type ElementMeta = {
  tag: string;
  /** Native React component, or framework-free custom element with a React wrapper. */
  kind: "react" | "element";
  name: string;
  component: string;
  collection: string;
  slug: string;
  title: string;
  description: string[];
  tryText: string | null;
  group: string | null;
  stage: string;
  stageClass: string;
  layout: "center" | "fill" | "wide";
  /** Markup for the usage example, when it differs from the demo `stage`. */
  markup: string | null;
  /** React props (native React components). */
  props: PropMeta[];
  attributes: AttributeMeta[];
  events: EventMeta[];
  methods: string[];
  observed: string[];
  /** Docs playground controls. */
  controls: ControlMeta[];
  /** Base props for the docs playground (native React components). */
  playgroundProps: Record<string, unknown>;
  formAssociated: boolean;
  /** `input`: shows your data (demo data until you pass it). `demo`: shows invented data only. `null`: shows no data. */
  data: "input" | "demo" | null;
  /** One sentence on what the data is and what can be set. */
  dataNote: string | null;
  nested: string[];
  added: string;
  /** Files for a manual install, in order. */
  files: RegistryFile[];
  /** `html` is null for native React components. */
  usage: { react: string; html: string | null; uses: string[] };
};

/** One collection, as scripts/catalog.mjs writes it to src/generated/collections.json. */
export type CollectionMeta = {
  slug: string;
  title: string;
  prefix: string;
  summary: string;
  description: string;
  count: number;
  /** Native React components, custom elements, or both. */
  kind: "react" | "element" | "mixed";
  groups: string[];
  updated: string;
};

// generated by scripts/catalog.mjs; the JSON is typed by its writer, not inferred from the file
/** Every component, in catalog order. */
export const elements = elementsJson as unknown as ElementMeta[];
/** The public collections, in catalog order. */
export const collections = collectionsJson as unknown as CollectionMeta[];

export const totalComponents = elements.length;

const byTag = new Map(elements.map((e) => [e.tag, e]));
const byPath = new Map(elements.map((e) => [`${e.collection}/${e.slug}`, e]));
const catalogOrder = new Map(elements.map((e, i) => [e.tag, i]));

/** A component by its tag, e.g. `hf-gauge`. */
export const getElement = (tag: string) => byTag.get(tag);
/** A component by its page path, e.g. `pixel-hd` and `gauge`. */
export const getElementByPath = (collection: string, slug: string) => byPath.get(`${collection}/${slug}`);
export const getCollection = (slug: string) => collections.find((c) => c.slug === slug);
/** The components of one collection, in catalog order. */
export const elementsIn = (collection: string) => elements.filter((e) => e.collection === collection);

/** The page of a component. */
export const elementHref = (e: Pick<ElementMeta, "collection" | "slug">) => `/components/${e.collection}/${e.slug}`;

/** Newest first: by date added, then reverse catalog order. */
export const newest = (n = 12) =>
  [...elements]
    .sort((a, b) => b.added.localeCompare(a.added) || (catalogOrder.get(b.tag) ?? 0) - (catalogOrder.get(a.tag) ?? 0))
    .slice(0, n);

/** The previous and next component in the same collection. */
export function siblings(e: ElementMeta) {
  const list = elementsIn(e.collection);
  const i = list.findIndex((x) => x.tag === e.tag);
  return { prev: i > 0 ? list[i - 1] : null, next: i < list.length - 1 ? list[i + 1] : null };
}

/** Related: same group first, then same collection. */
export function related(e: ElementMeta, n = 4) {
  const same = elementsIn(e.collection).filter((x) => x.tag !== e.tag);
  const group = same.filter((x) => x.group === e.group);
  const rest = same.filter((x) => x.group !== e.group);
  return [...group, ...rest].slice(0, n);
}

/** The component that best introduces each collection, shown on its card. */
const SIGNATURE: Record<string, string> = {
  interaction: "effort-slider",
  "pixel-lab": "px-orb",
  "pixel-ui": "px-otp",
  "pixel-hd": "hf-gauge",
  location: "geo-globe",
};
/** The signature component of a collection. */
export const signatureOf = (collection: string) => {
  const tag = SIGNATURE[collection];
  return tag ? byTag.get(tag) : undefined;
};
