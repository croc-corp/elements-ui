/** One entry of /search.json. */
export type SearchEntry = {
  id: string;
  kind: "page" | "component" | "heading" | "collection";
  title: string;
  url: string;
  description?: string;
  section?: string;
  tag?: string;
  collection?: string;
  keywords?: string;
};

let index: Promise<SearchEntry[]> | null = null;

/** The search index, fetched once per page; a failed fetch is forgotten so the next open retries. */
function loadIndex() {
  index ??= fetch("/search.json")
    .then((r) => {
      if (!r.ok) throw new Error(`/search.json answered ${r.status}`);
      // generated by our own route (src/app/search.json/route.ts)
      return r.json() as Promise<SearchEntry[]>;
    })
    .catch((error: unknown) => {
      index = null;
      throw error;
    });
  return index;
}

/** Whether the focused text field has a selection, so Ctrl+C / ⌘C should copy it rather than the install command. */
function hasTextSelection() {
  const active = document.activeElement;
  if (active instanceof HTMLInputElement || active instanceof HTMLTextAreaElement)
    return active.selectionStart !== active.selectionEnd;
  return Boolean(window.getSelection()?.toString());
}

/** The ⌘K palette: guides, headings, collections, components and a few actions, with a preview pane. */
export function CommandMenu({ open, onOpenChange }: { open: boolean; onOpenChange: (v: boolean) => void }) {
  const router = useRouter();
  const { resolved, setPref } = useTheme();
  const modifier = useModifierKey();
  const [entries, setEntries] = React.useState<SearchEntry[] | null>(null);
  const [failed, setFailed] = React.useState(false);
  const [query, setQuery] = React.useState("");
  const [value, setValue] = React.useState("");
  const [copied, setCopied] = React.useState<string | null>(null);
  const copiedTimer = React.useRef<number | undefined>(undefined);
  React.useEffect(() => () => window.clearTimeout(copiedTimer.current), []);

  // every opening starts with an empty query and retries a failed index (adjusted during render)
  const [wasOpen, setWasOpen] = React.useState(open);
  if (open !== wasOpen) {
    setWasOpen(open);
    if (open) {
      setQuery("");
      setFailed(false);
    }
  }

  React.useEffect(() => {
    if (!open || entries) return;
    let live = true;
    loadIndex()
      .then((loaded) => live && setEntries(loaded))
      .catch(() => live && setFailed(true));
    return () => {
      live = false;
    };
  }, [open, entries]);

  const go = (url: string) => {
    onOpenChange(false);
    if (url.startsWith("http")) window.open(url, "_blank", "noopener,noreferrer");
    else router.push(url);
  };

  const copyInstall = React.useCallback(async (tag: string) => {
    const cmd = `npx shadcn@latest add ${site.registry.namespace}/${tag}`;
    try {
      await navigator.clipboard.writeText(cmd);
      setCopied(tag);
      track("copy_install", tag, { source: "search" });
      window.clearTimeout(copiedTimer.current);
      copiedTimer.current = window.setTimeout(() => setCopied(null), 1400);
    } catch {
      // the clipboard can be blocked; the command stays visible in the preview pane
    }
  }, []);

  const selected = entries?.find((e) => e.id === value);

  React.useEffect(() => {
    if (!open) return;
    const onKey = (e: KeyboardEvent) => {
      if ((e.metaKey || e.ctrlKey) && e.key.toLowerCase() === "c" && selected?.tag && !hasTextSelection()) {
        e.preventDefault();
        void copyInstall(selected.tag);
      }
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [open, selected, copyInstall]);

  const pages = entries?.filter((e) => e.kind === "page") ?? [];
  const collections = entries?.filter((e) => e.kind === "collection") ?? [];
  const components = entries?.filter((e) => e.kind === "component") ?? [];
  const headings = query.length > 1 ? (entries?.filter((e) => e.kind === "heading") ?? []) : [];
  const groups = [...new Set(components.map((c) => c.section ?? ""))];

  return (
    <Command.Dialog
      open={open}
      onOpenChange={onOpenChange}
      label="Search LumeSec Elements"
      value={value}
      onValueChange={setValue}
      loop
      overlayClassName="fixed inset-0 z-[90] bg-background/60 backdrop-blur-sm data-[state=open]:animate-[sl-fade_.2s_ease]"
      contentClassName="fixed left-1/2 top-[12vh] z-[100] w-[min(860px,calc(100vw-24px))] -translate-x-1/2 overflow-hidden rounded-2xl border border-border bg-card shadow-[var(--shadow-pop)] data-[state=open]:animate-[sl-fade-up_.28s_var(--ease-expo)]"
      filter={(v, search, keywords) => score(v, search, keywords)}
    >
      <div className="flex items-center gap-3 border-b border-border px-4">
        <SearchIcon className="shrink-0 text-muted-foreground" />
        <Command.Input
          value={query}
          onValueChange={setQuery}
          placeholder="Search components, guides and headings…"
          className="h-14 flex-1 bg-transparent text-[15px] outline-none placeholder:text-muted-foreground"
        />
        <kbd className="sl-kbd">Esc</kbd>
      </div>
      <div className="grid md:grid-cols-[minmax(0,1fr)_300px]">
        <Command.List className="h-[min(460px,60vh)] overflow-y-auto overscroll-contain p-2 [&_[cmdk-group-heading]]:px-2.5 [&_[cmdk-group-heading]]:pt-3 [&_[cmdk-group-heading]]:pb-1.5 [&_[cmdk-group-heading]]:font-mono [&_[cmdk-group-heading]]:text-[11px] [&_[cmdk-group-heading]]:text-muted-foreground">
          {!entries && (
            <div className="px-3 py-8 text-center font-mono text-[12px] text-muted-foreground" role="status">
              {failed
                ? "The search index could not be loaded. Close and open the search to try again."
                : "Loading index…"}
            </div>
          )}
          <Command.Empty className="px-3 py-10 text-center text-[14px] text-muted-foreground">
            No results for “{query}”.
          </Command.Empty>
          {pages.length > 0 && (
            <Command.Group heading="Guides">
              {pages.map((p) => (
                <Item key={p.id} entry={p} onSelect={() => go(p.url)} icon={<BookIcon />} />
              ))}
            </Command.Group>
          )}
          {collections.length > 0 && (
            <Command.Group heading="Collections">
              {collections.map((p) => (
                <Item
                  key={p.id}
                  entry={p}
                  onSelect={() => go(p.url)}
                  icon={<CollectionGlyph slug={p.collection ?? ""} />}
                />
              ))}
            </Command.Group>
          )}
          {groups.map((g) => (
            <Command.Group key={g} heading={g}>
              {components
                .filter((c) => (c.section ?? "") === g)
                .map((c) => (
                  <Item
                    key={c.id}
                    entry={c}
                    onSelect={() => go(c.url)}
                    icon={<CollectionGlyph slug={c.collection ?? ""} />}
                  />
                ))}
            </Command.Group>
          ))}
          {headings.length > 0 && (
            <Command.Group heading="On pages">
              {headings.map((h) => (
                <Item
                  key={h.id}
                  entry={h}
                  onSelect={() => go(h.url)}
                  icon={<span className="font-mono text-[12px]">#</span>}
                />
              ))}
            </Command.Group>
          )}
          <Command.Group heading="Actions">
            <Command.Item
              value="action:theme"
              keywords={["theme", "dark", "light", "mode"]}
              onSelect={() => {
                setPref(resolved === "dark" ? "light" : "dark");
              }}
              className={itemClass}
            >
              <span className="flex size-7 items-center justify-center rounded-md border border-border bg-background text-muted-foreground">
                {resolved === "dark" ? <SunIcon /> : <MoonIcon />}
              </span>
              Switch to {resolved === "dark" ? "light" : "dark"} theme
            </Command.Item>
            <Command.Item
              value="action:registry"
              keywords={["registry", "shadcn", "components.json", "namespace"]}
              onSelect={() => go("/docs/installation")}
              className={itemClass}
            >
              <span className="flex size-7 items-center justify-center rounded-md border border-border bg-background text-muted-foreground">
                <TerminalIcon />
              </span>
              Add the {site.registry.namespace} registry to components.json
            </Command.Item>
            <Command.Item
              value="action:github"
              keywords={["github", "source", "repository"]}
              onSelect={() => go(site.repo.url)}
              className={itemClass}
            >
              <span className="flex size-7 items-center justify-center rounded-md border border-border bg-background text-muted-foreground">
                <GitHubIcon />
              </span>
              Open the GitHub repository
            </Command.Item>
          </Command.Group>
        </Command.List>
        <aside className="hidden border-l border-border bg-surface/50 p-5 md:block" aria-live="polite">
          {selected ? (
            <div key={selected.id} className="page-enter">
              <p className="font-mono text-[11px] text-muted-foreground">
                {selected.kind === "component"
                  ? selected.section
                  : selected.kind === "heading"
                    ? "Heading"
                    : selected.kind === "collection"
                      ? "Collection"
                      : "Guide"}
              </p>
              <p className="mt-2 text-[17px] font-medium tracking-tight">{selected.title}</p>
              {selected.tag && (
                <p className="mt-1 font-mono text-[12px] text-muted-foreground">&lt;{selected.tag}&gt;</p>
              )}
              {selected.description && (
                <p className="mt-3 line-clamp-6 text-[13px] leading-relaxed text-muted-foreground">
                  {selected.description}
                </p>
              )}
              {selected.tag && (
                <button
                  type="button"
                  onClick={() => {
                    if (selected.tag) void copyInstall(selected.tag);
                  }}
                  className="mt-5 flex w-full items-center gap-2 rounded-lg border border-border bg-background px-3 py-2 text-left font-mono text-[11.5px] transition-colors hover:border-input"
                >
                  <span className="text-muted-foreground">$</span>
                  <span className="min-w-0 flex-1 truncate">
                    shadcn add {site.registry.namespace}/{selected.tag}
                  </span>
                  {copied === selected.tag ? (
                    <CheckIcon size={14} className="text-success" />
                  ) : (
                    <CopyIcon size={14} className="text-muted-foreground" />
                  )}
                </button>
              )}
            </div>
          ) : (
            <p className="text-[13px] text-muted-foreground">Type to search. Arrow keys to move.</p>
          )}
        </aside>
      </div>
      <div className="flex items-center gap-4 border-t border-border px-4 py-2.5 font-mono text-[11px] text-muted-foreground">
        <span className="flex items-center gap-1.5">
          <kbd className="sl-kbd">↑</kbd>
          <kbd className="sl-kbd">↓</kbd> move
        </span>
        <span className="flex items-center gap-1.5">
          <kbd className="sl-kbd">↵</kbd> open
        </span>
        {selected?.tag && (
          <span className="flex items-center gap-1.5">
            <kbd className="sl-kbd">{modifier}</kbd>
            <kbd className="sl-kbd">C</kbd> copy install
          </span>
        )}
        <span className="ml-auto hidden sm:block">
          {entries ? `${entries.filter((e) => e.kind === "component").length} components indexed` : ""}
        </span>
      </div>
    </Command.Dialog>
  );
}

const itemClass =
  "group flex cursor-pointer items-center gap-3 rounded-lg px-2.5 py-2 text-[14px] text-foreground/90 outline-none data-[selected=true]:bg-muted data-[selected=true]:text-foreground";

function Item({ entry, onSelect, icon }: { entry: SearchEntry; onSelect: () => void; icon: React.ReactNode }) {
  return (
    <Command.Item
      value={entry.id}
      keywords={[entry.title, entry.tag ?? "", entry.keywords ?? "", entry.section ?? ""]}
      onSelect={onSelect}
      className={itemClass}
    >
      <span className="flex size-7 shrink-0 items-center justify-center rounded-md border border-border bg-background text-muted-foreground">
        {icon}
      </span>
      <span className="min-w-0 flex-1 truncate">
        {entry.title}
        {entry.kind === "heading" && entry.section && (
          <span className="ml-2 text-muted-foreground">{entry.section}</span>
        )}
      </span>
      {entry.tag && <span className="hidden font-mono text-[11px] text-muted-foreground sm:block">{entry.tag}</span>}
      <ArrowRightIcon
        size={14}
        className={cn(
          "text-muted-foreground opacity-0 transition-all group-data-[selected=true]:translate-x-0.5 group-data-[selected=true]:opacity-100",
        )}
      />
    </Command.Item>
  );
}

/** Ranking: exact and prefix matches on the title or tag beat fuzzy matches in keywords. */
function score(value: string, search: string, keywords?: string[]) {
  const q = search.trim().toLowerCase();
  if (!q) return value.startsWith("heading:") ? 0 : 1;
  const hay = [value, ...(keywords ?? [])].join(" ").toLowerCase();
  const title = (keywords?.[0] ?? value).toLowerCase();
  const tag = (keywords?.[1] ?? "").toLowerCase();
  if (title === q || tag === q) return 1;
  if (title.startsWith(q) || tag.startsWith(q) || tag.endsWith(`-${q}`)) return 0.9;
  if (title.includes(q) || tag.includes(q)) return 0.75;
  const words = q.split(/\s+/);
  if (words.every((w) => hay.includes(w))) return 0.5;
  return 0;
}
